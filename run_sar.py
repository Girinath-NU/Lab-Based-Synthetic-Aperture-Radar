#!/usr/bin/env python3
"""
run_sar.py  —  Automated SAR aperture data collection launcher
===============================================================
Drives fmcw_sar_robust.py (generated by GRC from fmcw_sar_robust.grc)
across all aperture positions, handles file naming, validates output,
and assembles the final data matrix for MATLAB.

Usage:
    1. Open fmcw_sar_robust.grc in gnuradio-companion
    2. Press 'Generate' (F5) to produce fmcw_sar_robust.py
    3. Run:  python3 run_sar.py

Output:
    ~/sar_data/pos_XXXX.bin   — raw beat IQ per position
    ~/sar_data/sar_matrix.npy — assembled [N_pos x N_capture] matrix
    ~/sar_data/sar_config.json — all parameters for MATLAB
"""

import os, sys, json, time, signal, subprocess, struct
import numpy as np

# ─────────────────────────────────────────────────────────────────────────────
#  PARAMETERS  — must match fmcw_sar_robust.grc variables exactly
# ─────────────────────────────────────────────────────────────────────────────
PARAMS = {
    "samp_rate"   : 5_000_000,   # Hz
    "center_freq" : 6_000_000_000,# Hz
    "chirp_bw"    : 5_000_000,   # Hz
    "sweep_time"  : 0.001,        # s
    "tx_gain"     : 70,           # dB
    "rx_gain"     : 50,           # dB
    "n_chirps"    : 32,           # chirps per position (averaged in MATLAB)
    "n_positions" : 64,           # aperture positions
    "dx"          : 0.015,        # m — step size (15 mm = lambda/2 at ~10 GHz)
    "target_range": 2.5,          # m — approximate target distance
}

# Derived
PARAMS["n_samp_chirp"] = int(PARAMS["samp_rate"] * PARAMS["sweep_time"])
PARAMS["n_capture"]    = PARAMS["n_chirps"] * PARAMS["n_samp_chirp"]
PARAMS["n_settle"]     = int(0.3 * PARAMS["samp_rate"])
PARAMS["file_size_bytes"] = PARAMS["n_capture"] * 8  # 2x float32 per sample
PARAMS["aperture_length"] = PARAMS["n_positions"] * PARAMS["dx"]
PARAMS["wavelength"]   = 3e8 / PARAMS["center_freq"]
PARAMS["range_res"]    = 3e8 / (2 * PARAMS["chirp_bw"])
cr_res = (PARAMS["wavelength"] * PARAMS["target_range"]) / PARAMS["aperture_length"]
PARAMS["crossrange_res"] = cr_res
PARAMS["grc_script"]   = os.path.expanduser("~/fmcw_sar_robust.py")
PARAMS["output_dir"]   = os.path.expanduser("~/sar_data")

# ─────────────────────────────────────────────────────────────────────────────
#  HELPERS
# ─────────────────────────────────────────────────────────────────────────────
RESET  = "\033[0m"
GREEN  = "\033[92m"
YELLOW = "\033[93m"
RED    = "\033[91m"
CYAN   = "\033[96m"
BOLD   = "\033[1m"

def log(msg, color=RESET):
    t = time.strftime("%H:%M:%S")
    print(f"{color}[{t}] {msg}{RESET}")

def banner():
    print(f"\n{BOLD}{CYAN}{'='*60}")
    print("  FMCW SAR Aperture Collection")
    print(f"  Center: {PARAMS['center_freq']/1e9:.1f} GHz  "
          f"BW: {PARAMS['chirp_bw']/1e6:.0f} MHz  "
          f"SR: {PARAMS['samp_rate']/1e6:.0f} MSPS")
    print(f"  Positions: {PARAMS['n_positions']}  "
          f"Step: {PARAMS['dx']*1000:.0f} mm  "
          f"Aperture: {PARAMS['aperture_length']*100:.0f} cm")
    print(f"  Range res: {PARAMS['range_res']:.2f} m  "
          f"CR res: {PARAMS['crossrange_res']*100:.1f} cm")
    print(f"  Per-position capture: {PARAMS['n_capture']:,} samples "
          f"= {PARAMS['file_size_bytes']/1024:.0f} KB")
    print(f"  Settling skip: {PARAMS['n_settle']/PARAMS['samp_rate']*1000:.0f} ms")
    print(f"{'='*60}{RESET}\n")

def validate_file(path, expected_bytes):
    """Check file exists and has correct size."""
    if not os.path.exists(path):
        return False, "file not found"
    actual = os.path.getsize(path)
    if actual != expected_bytes:
        return False, f"wrong size: got {actual} B, expected {expected_bytes} B"
    # Quick sanity: read first 16 bytes and check they are finite floats
    with open(path, "rb") as f:
        raw = f.read(16)
    if len(raw) < 16:
        return False, "file too short to read header"
    vals = struct.unpack("4f", raw)
    if any(not (-1e6 < v < 1e6) for v in vals):
        return False, f"suspicious values in header: {vals}"
    return True, "ok"

def load_beat(path, n_capture):
    """Load binary IQ file into complex numpy array."""
    raw = np.fromfile(path, dtype=np.float32)
    if len(raw) < n_capture * 2:
        raise ValueError(f"File {path} has {len(raw)//2} samples, "
                         f"expected {n_capture}")
    raw = raw[:n_capture * 2]
    return raw[0::2] + 1j * raw[1::2]

def run_grc_position(pos_idx, out_path, max_retries=3):
    """
    Run the GRC-generated script for one aperture position.
    Forces the process to close if WSL2/UHD hangs on teardown.
    """
    script = PARAMS["grc_script"]
    if not os.path.exists(script):
        log(f"GRC script not found: {script}", RED)
        sys.exit(1)

    # 10 seconds is plenty of time to capture 640k samples
    timeout_s = 10 

    for attempt in range(1, max_retries + 1):
        if attempt > 1:
            log(f"   Retry {attempt}/{max_retries} for position {pos_idx}...", YELLOW)
            time.sleep(2.0)

        log(f"   Running capture (timeout {timeout_s}s)...", CYAN)
        
        # Start the radio
        proc = subprocess.Popen([sys.executable, script, "-o", out_path])
        
        try:
            # Wait for it to finish naturally
            proc.wait(timeout=timeout_s)
        except subprocess.TimeoutExpired:
            # WSL2 UHD teardown hang detected. Send Graceful Ctrl+C to flush buffers!
            log("   Hardware hung on shutdown. Sending graceful stop to save file...", YELLOW)
            proc.send_signal(signal.SIGINT)
            
            try:
                # Give GNU Radio 3 seconds to save the file to disk
                proc.wait(timeout=3)
            except subprocess.TimeoutExpired:
                # If it still refuses to close after saving, now we force kill
                proc.kill()

        # Check if the file was successfully written
        ok, msg = validate_file(out_path, PARAMS["file_size_bytes"])

        # Check if the Head block successfully wrote our file before the hang
        ok, msg = validate_file(out_path, PARAMS["file_size_bytes"])
        
        if ok:
            return True
        else:
            log(f"   Capture incomplete ({msg}). Retrying...", RED)
            if os.path.exists(out_path):
                os.remove(out_path)

    return False
# ─────────────────────────────────────────────────────────────────────────────
#  MAIN COLLECTION LOOP
# ─────────────────────────────────────────────────────────────────────────────
def main():
    banner()

    os.makedirs(PARAMS["output_dir"], exist_ok=True)
    config_path = os.path.join(PARAMS["output_dir"], "sar_config.json")
    matrix_path = os.path.join(PARAMS["output_dir"], "sar_matrix.npy")

    # Save config for MATLAB before starting
    with open(config_path, "w") as f:
        json.dump(PARAMS, f, indent=2)
    log(f"Config saved to {config_path}", GREEN)

    # Pre-flight checks
    log("Pre-flight checks...", CYAN)
    if not os.path.exists(PARAMS["grc_script"]):
        log(f"ERROR: {PARAMS['grc_script']} not found.", RED)
        log("Open fmcw_sar_robust.grc in GNU Radio Companion", RED)
        log("Press F5 (Generate) to produce the Python script, then re-run this.", RED)
        sys.exit(1)

    try:
        import uhd
        log("  UHD Python bindings: OK", GREEN)
    except ImportError:
        log("  WARNING: cannot import uhd — will only know at runtime", YELLOW)

    far_field = 2 * (0.241**2) / PARAMS["wavelength"]
    log(f"  Far-field distance at {PARAMS['center_freq']/1e9:.1f} GHz: "
        f"{far_field:.2f} m", CYAN)
    if PARAMS["target_range"] < far_field:
        log(f"  WARNING: target_range ({PARAMS['target_range']}m) < far-field "
            f"({far_field:.2f}m). Use back-projection (not FFT) in MATLAB.", YELLOW)

    print()
    print(f"{BOLD}Place target at ~{PARAMS['target_range']} m from antenna.{RESET}")
    print(f"{BOLD}Mount antenna at position 0 (x = 0.00 cm).{RESET}")
    input(f"\n{BOLD}Press Enter to start collection...{RESET}\n")

    collected = []
    failed    = []
    t_start   = time.time()

    for pos in range(PARAMS["n_positions"]):
        x_cm = pos * PARAMS["dx"] * 100
        out_path = os.path.join(PARAMS["output_dir"], f"pos_{pos:04d}.bin")

        print()
        print(f"{BOLD}{'─'*50}{RESET}")
        log(f"Position {pos+1}/{PARAMS['n_positions']}  "
            f"x = {x_cm:.1f} cm", BOLD + CYAN)

        # Prompt for manual movement (replace with motor command if automated)
        if pos == 0:
            log("  Antenna already at x = 0.00 cm", GREEN)
        else:
            prev_cm = (pos - 1) * PARAMS["dx"] * 100
            print(f"\n  Move antenna from x = {prev_cm:.1f} cm  →  x = {x_cm:.1f} cm")
            print(f"  (advance {PARAMS['dx']*1000:.0f} mm = {PARAMS['dx']*10:.1f} cm)")
            input("  Press Enter when in position...")

        # If file already exists (resuming), validate and skip
        if os.path.exists(out_path):
            ok, msg = validate_file(out_path, PARAMS["file_size_bytes"])
            if ok:
                log(f"  File already exists and valid — skipping capture", YELLOW)
                collected.append(pos)
                continue
            else:
                log(f"  Existing file invalid ({msg}), re-capturing", YELLOW)
                os.remove(out_path)

        # Run GRC capture
        t0 = time.time()
        success = run_grc_position(pos, out_path)
        elapsed = time.time() - t0

        if success:
            size_kb = os.path.getsize(out_path) / 1024
            log(f"  Captured {PARAMS['n_capture']:,} samples "
                f"({size_kb:.0f} KB) in {elapsed:.1f}s", GREEN)
            collected.append(pos)
        else:
            log(f"  FAILED after 3 retries — skipping position {pos}", RED)
            failed.append(pos)

        # ETA
        done  = pos + 1
        total = PARAMS["n_positions"]
        rate  = done / (time.time() - t_start)
        eta_s = (total - done) / rate if rate > 0 else 0
        log(f"  Progress: {done}/{total}  ETA: {eta_s/60:.1f} min", CYAN)

    # ── Assemble matrix ───────────────────────────────────────────────────────
    print()
    log("Collection complete. Assembling SAR matrix...", BOLD + GREEN)
    log(f"  Collected: {len(collected)}/{PARAMS['n_positions']} positions", GREEN)
    if failed:
        log(f"  Failed positions: {failed}", RED)

    n_cap = PARAMS["n_capture"]
    S = np.zeros((PARAMS["n_positions"], n_cap), dtype=np.complex64)

    for pos in collected:
        path = os.path.join(PARAMS["output_dir"], f"pos_{pos:04d}.bin")
        try:
            iq = load_beat(path, n_cap)
            S[pos, :] = iq
        except Exception as e:
            log(f"  Error loading pos {pos}: {e}", RED)

    np.save(matrix_path, S)
    log(f"SAR matrix saved: {matrix_path}  shape={S.shape}  "
        f"dtype={S.dtype}", GREEN)
    log(f"Config saved:     {config_path}", GREEN)
    log("Pass both files to sar_image.m in MATLAB.", BOLD)

    total_time = time.time() - t_start
    log(f"Total time: {total_time/60:.1f} minutes", CYAN)


if __name__ == "__main__":
    main()
